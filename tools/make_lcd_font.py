"""Convert gui_resources/RolandFont.png (16x16 grid of 5x7 glyphs, indexed by
character code) into a C++ table for the dot-matrix LCD renderer.

Run from anywhere:  python3 tools/make_lcd_font.py
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
image = Image.open(ROOT / "gui_resources" / "RolandFont.png").convert("RGBA")

rows = []
for code in range(256):
    cx, cy = (code % 16) * 5, (code // 16) * 7
    glyph = []
    for y in range(7):
        bits = 0
        for x in range(5):
            if image.getpixel((cx + x, cy + y))[3] > 128:
                bits |= 0x10 >> x
        glyph.append(f"0x{bits:02X}")
    rows.append("    { " + ", ".join(glyph) + " }, // " + str(code))

out = ROOT / "cpp" / "app" / "source" / "ui" / "LcdFontData.h"
out.write_text(
    "// Generated by tools/make_lcd_font.py from gui_resources/RolandFont.png. Do not edit.\n"
    "#pragma once\n\n#include <cstdint>\n\nnamespace sc88::ui {\n\n"
    "// 256 glyphs, 7 rows each; bit 4 is the leftmost of the 5 columns.\n"
    "inline constexpr uint8_t kLcdFont[256][7] = {\n" + "\n".join(rows) + "\n};\n\n}\n"
)
print("wrote", out.relative_to(ROOT))
